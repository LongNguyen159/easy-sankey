const fs=require('node:fs');
const path=require('node:path');
const ts=require('typescript');
const root=path.resolve(__dirname,'..');
const source=path.join(root,'electron/api/operations.ts');
const output=path.join(root,'electron/storage/operations.generated.js');
function write(file,text){
 if(fs.existsSync(file)&&fs.readFileSync(file,'utf8')===text)return;
 const temporary=`${file}.tmp-${process.pid}`;
 fs.writeFileSync(temporary,text);fs.renameSync(temporary,file);
}
const program=ts.createProgram([source],{strict:true,target:ts.ScriptTarget.ES2022,module:ts.ModuleKind.CommonJS,skipLibCheck:true,esModuleInterop:true});
const diagnostics=ts.getPreEmitDiagnostics(program);
if(diagnostics.length)throw new Error(ts.formatDiagnosticsWithColorAndContext(diagnostics,{getCurrentDirectory:()=>root,getCanonicalFileName:file=>file,getNewLine:()=>"\n"}));
const code=ts.transpileModule(fs.readFileSync(source,'utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText;
write(output,'// Generated by scripts/generate-database-api.cjs. Edit electron/api/operations.ts.\n'+code);
delete require.cache[output];
const {operations}=require(output);
function flatten(tree,prefix=[]){return Object.entries(tree).flatMap(([key,value])=>typeof value.run==='function'?[{path:[...prefix,key],operation:value}]:flatten(value,[...prefix,key]));}
const routes=flatten(operations);
if(new Set(routes.map(route=>route.operation.channel)).size!==routes.length)throw new Error('Duplicate database channel.');
const client=`// Generated database bridge: only declared channels are exposed.
function createDatabaseClient() {
  const client={};
  for(const [path,channel] of ${JSON.stringify(routes.map(({path,operation})=>[path,operation.channel]))}) {
    let target=client;
    for(const key of path.slice(0,-1))target=target[key]??=( {} );
    target[path[path.length-1]]=payload=>ipcRenderer.invoke(channel,payload);
  }
  return client;
}`;
const template=fs.readFileSync(path.join(root,'electron/api/preload.template.cjs'),'utf8');
write(path.join(root,'preload.js'),'// Generated by scripts/generate-database-api.cjs. Edit electron/api/preload.template.cjs.\n'+template.replace('/* DATABASE_CLIENT */',client));
const checker=program.getTypeChecker();
const file=program.getSourceFile(source);
const declaration=file.statements.find(statement=>ts.isVariableStatement(statement)&&statement.declarationList.declarations.some(declaration=>declaration.name.getText(file)==='operations')).declarationList.declarations[0];
let lines=['# Database API reference','','Generated from `electron/api/operations.ts`. Do not edit this file manually.','','All methods are asynchronous and available under `window.electronAPI.database`.','Inputs are checked in the main process before their handler executes. Domain validation and transactions remain in the database implementation.','','| Operation | Input | Result | Behavior |','| --- | --- | --- | --- |'];
for(const route of routes){let type=checker.getTypeAtLocation(declaration.name);for(const key of route.path){const symbol=type.getProperty(key);type=checker.getTypeOfSymbolAtLocation(symbol,declaration);}const args=checker.getTypeArguments(type);const format=t=>checker.typeToString(t,undefined,ts.TypeFormatFlags.NoTruncation).replaceAll('|','\\|');lines.push(`| \`${route.path.join('.')}\` | \`${format(args[0])}\` | \`${format(args[1])}\` | ${route.operation.description} |`);}
write(path.join(root,'docs/database-api.md'),lines.join('\n')+'\n');
